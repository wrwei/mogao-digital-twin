"""Apply Hampel-style outlier replacement to the remaining spots in
experiments/敦煌变化数据_predicted.xlsx 恒温 sheet (chamber-arm), matching
the noise-reduction the user already applied by hand to HR.1, HR.2, HR.3.

Algorithm per spot per channel (L*, a*, b*):
  1. For each interior point i, compute the median m_i of the 3-point
     centered window [i-1, i, i+1] over the available values.
  2. Compute the median absolute deviation (MAD) over the same window.
  3. If |x_i - m_i| > k * (MAD + epsilon) AND |x_i - m_i| > floor,
     replace x_i with m_i. Otherwise leave it alone.
  4. Endpoints (first and last) are left unchanged so the day-0 baseline
     and the day-34 endpoint are preserved.

Parameters tuned so that HR.1 4.26 a* = 29.05 (median neighbours ~34)
gets caught, while small fluctuations (~0.3 ΔE*) are left alone.

Defaults: window = 3, k = 1.5, floor = 0.6 per channel.

Spots smoothed: HG.1, HG.2, HG.3, HB.1, HB.2, HB.3, HTR.1, HTR.2,
                HTG.1, HTG.2, HTB.1, HTB.2 (all non-HR spots in 恒温).

The 恒温恒湿 predicted sheet is NOT regenerated by this script; if the
user wants the predicted arm to reflect the smoothed chamber data it
should be regenerated by running _extend_180d.py (or a similar
RH-scaling) afterwards.

Output: overwrites experiments/敦煌变化数据_predicted.xlsx in place
(but writes a backup to experiments/敦煌变化数据_predicted.xlsx.bak first).
"""
import openpyxl
import shutil
import re
from openpyxl.styles import PatternFill

WINDOW = 3       # centered 3-point window
K_MAD = 3.0      # MAD multiplier threshold (raised from 1.5 — now catches only clear outliers)
FLOOR = 3.0      # absolute floor on deviation (raised from 0.6 — skip nudges <3 units)

DATE_RE = re.compile(r"^\s*\d+\.\d+\s*$")

def to_f(v):
    try:
        return float(v)
    except Exception:
        return None

def is_date(v):
    if v is None:
        return False
    return bool(DATE_RE.match(str(v).strip()))

# Spots to smooth (all non-HR spots in the chamber arm)
TARGETS = [
    ("G",  [11, 14, 17]),  # malachite block, 3 spots
    ("B",  [20, 23, 26]),  # azurite block, 3 spots
    ("TR", [29, 32]),      # vermilion pedestal, 2 spots
    ("TG", [35, 38]),      # malachite pedestal, 2 spots
    ("TB", [41, 44]),      # azurite pedestal, 2 spots
]

src = "experiments/敦煌变化数据_predicted.xlsx"
bak = src + ".bak"

print(f"Backing up {src} -> {bak}")
shutil.copy2(src, bak)

wb = openpyxl.load_workbook(src)
ws = wb["恒温"]

# Determine the data rows (date column non-empty and parseable)
rows = [r for r in range(4, ws.max_row + 1) if is_date(ws.cell(r, 1).value)]
print(f"Data rows: {len(rows)} (rows {rows[0]}..{rows[-1]})")

smoothed_fill = PatternFill(start_color="FFE9D6", end_color="FFE9D6", fill_type="solid")

def hampel_replace(series):
    """Return (new_series, changes) where new_series has interior outliers
    replaced by their 3-point centered median."""
    n = len(series)
    out = list(series)
    changes = []
    for i in range(1, n - 1):  # skip endpoints
        x = series[i]
        nbrs = [series[i - 1], series[i + 1]]
        valid_nbrs = [v for v in nbrs if v is not None]
        if x is None or not valid_nbrs:
            continue
        window_vals = [series[i - 1], series[i], series[i + 1]]
        valid_win = [v for v in window_vals if v is not None]
        if len(valid_win) < 2:
            continue
        m = sorted(valid_win)[len(valid_win) // 2]  # median (rough on ties)
        # MAD over the window
        absdev = sorted(abs(v - m) for v in valid_win)
        mad = absdev[len(absdev) // 2]
        # Replacement condition
        dev = abs(x - m)
        if dev > FLOOR and dev > K_MAD * (mad + 1e-6):
            out[i] = round(m, 2)
            changes.append((i, x, m))
    return out, changes

print()
print(f"{'Group':6s} {'Spot':5s} {'Chan':5s} {'Changes (row -> new val)':40s}")
print("-" * 70)

total_changes = 0
for grp, cols in TARGETS:
    for sidx, c in enumerate(cols):
        for ch_off, ch_name in [(0, "L*"), (1, "a*"), (2, "b*")]:
            # Read series
            series = [to_f(ws.cell(r, c + ch_off).value) for r in rows]
            new_series, changes = hampel_replace(series)
            if not changes:
                continue
            # Write changes back
            change_strs = []
            for i, old, new in changes:
                r = rows[i]
                ws.cell(r, c + ch_off).value = new
                ws.cell(r, c + ch_off).fill = smoothed_fill
                change_strs.append(f"r{r} {old:.2f}->{new:.2f}")
            print(f"{grp:6s} {sidx + 1:>5d} {ch_name:5s} {', '.join(change_strs)}")
            total_changes += len(changes)

print()
print(f"Total cells smoothed: {total_changes}")
wb.save(src)
print(f"Saved -> {src}")
print(f"(Backup at {bak} if anything looks wrong.)")
