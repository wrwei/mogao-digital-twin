"""Consolidate the model-faithful dataset into a single clean workbook:
experiments/mogao_data_consolidated.xlsx

Sheets:
  README      - provenance + column dictionary
  data_long   - tidy: one row per (arm, spot, timepoint) with L*a*b*, ΔE, flags
  deltaE_mean - mean ΔE per (arm, pigment, geometry, day) with n spots

Reads experiments/mogao_data_model_faithful.xlsx (synthetic, gap-filled) and
experiments/_interp_days.json (which days are model-interpolated).
"""
import openpyxl, math, re, json, os
from openpyxl.styles import Font, PatternFill, Alignment

DATE_RE = re.compile(r"^\s*\d+\.\d+\s*$")
def to_f(v):
    try: return float(v)
    except Exception: return None
def is_date(v): return v is not None and bool(DATE_RE.match(str(v).strip()))
def date_to_day(d):
    m, day = str(d).strip().split("."); dpm=[31,28,31,30,31,30,31,31,30,31,30,31]
    return (sum(dpm[:int(m)-1]) + int(day)) - (sum(dpm[:3]) + 17)

spec_cols = {"R":[2,5,8],"G":[11,14,17],"B":[20,23,26],"TR":[29,32],"TG":[35,38],"TB":[41,44]}
PIGMENT   = {"R":"Vermilion","TR":"Vermilion","G":"Malachite","TG":"Malachite","B":"Azurite","TB":"Azurite"}
# 'T' in the label = Tile = BLOCK; no-T = PEDESTAL (lotus base). (Was swapped.)
GEOMETRY  = {"R":"pedestal","G":"pedestal","B":"pedestal","TR":"block","TG":"block","TB":"block"}
# 40C/80%RH (恒温恒湿) deliberately EXCLUDED: it was an unvalidated extrapolation
# (data-anchored, factor-2 RH uncertainty, dark-pathway mechanism doubtful) and has
# been discarded. Only the two experimentally-measured arms are kept.
# Both arms share the SAME ambient lighting; they differ only in temperature/humidity.
SHEETS = {
    "室温":    ("23C_40RH_room",    "23 C / 40%RH (room-temp arm)", "measured"),
    "恒温":    ("40C_10RH_chamber", "40 C / 10%RH (chamber arm)",   "measured"),
}

INTERP = set()
if os.path.exists("experiments/_interp_days.json"):
    INTERP = set(json.load(open("experiments/_interp_days.json"))["interp_days"])

src = "experiments/mogao_data_model_faithful.xlsx"
wb = openpyxl.load_workbook(src, data_only=True)

rows_out = []   # tidy long rows
for sh, (arm_code, condition, status) in SHEETS.items():
    ws = wb[sh]
    drows = [r for r in range(1, ws.max_row+1) if is_date(ws.cell(r,1).value)]
    days  = [date_to_day(ws.cell(r,1).value) for r in drows]
    for grp, cols in spec_cols.items():
        for sidx, c in enumerate(cols):
            label = ws.cell(2, c).value or f"{grp}.{sidx+1}"   # spot label from header row
            # baseline = day-0 L*a*b*
            r0 = drows[days.index(0)] if 0 in days else drows[0]
            L0,a0,b0 = (to_f(ws.cell(r0,c).value), to_f(ws.cell(r0,c+1).value), to_f(ws.cell(r0,c+2).value))
            for r, d in zip(drows, days):
                L,a,b = (to_f(ws.cell(r,c).value), to_f(ws.cell(r,c+1).value), to_f(ws.cell(r,c+2).value))
                dE = None
                if None not in (L,a,b,L0,a0,b0):
                    dE = round(math.sqrt((L-L0)**2+(a-a0)**2+(b-b0)**2), 2)
                ptype = "measured"   # gap-fill points not distinguished, per request
                rows_out.append([arm_code, condition, status, PIGMENT[grp], GEOMETRY[grp],
                                 str(label), str(ws.cell(r,1).value), d, L, a, b, dE, ptype])

def write_dE_formula(ws, rows):
    """Append rows, but write the deltaE cell (col L) as a live Excel formula
    referencing L*a*b* (cols I,J,K) vs each spot's own day-0 baseline row."""
    base = None
    for row in rows:
        ws.append(row); er = ws.max_row
        day, L, a, b = row[7], row[8], row[9], row[10]
        if day == 0:
            base = er; ws.cell(er, 12).value = 0
        elif base and None not in (L, a, b):
            ws.cell(er, 12).value = (f"=ROUND(SQRT((I{er}-I{base})^2+"
                                     f"(J{er}-J{base})^2+(K{er}-K{base})^2),2)")

# ---- write consolidated workbook ----
out = openpyxl.Workbook()
hdr_font = Font(bold=True, color="FFFFFF"); hdr_fill = PatternFill("solid", fgColor="365F91")
interp_fill = PatternFill("solid", fgColor="FFF3CD"); pred_fill = PatternFill("solid", fgColor="F3E5F5")

# README
rm = out.active; rm.title = "README"
readme = [
    ("Mogao pigment colour-change — consolidated dataset", True),
    ("", False),
    ("Source: experiments/mogao_data_model_faithful.xlsx (regenerated by _make_model_faithful_v2.py).", False),
    ("These values are MODEL-GENERATED (deterioration-model curves + measurement noise), NOT raw", False),
    ("instrument readings. Raw measurements live in experiments/mogao_data.xlsx (unmodified).", False),
    ("", False),
    ("Model: per-pigment Arrhenius Ea (vermilion 86.7 / azurite 57.3 / malachite 35.0 kJ, _validation.json)", False),
    ("       x Paltakari RH^0.8, thermal-only; anchored to the noise-corrected chamber signal.", False),
    ("       Measurement noise sigma = 0.7 dE/channel (independent).", False),
    ("       No photolytic pathway: both arms share the same ambient light, so light cannot", False),
    ("       differentiate them; vermilion is 40C-led on its high Ea (chemical model).", False),
    ("", False),
    ("point_type: all rows labelled 'measured' (gap-fill points not separately flagged).", False),
    ("", False),
    ("Arms: two experimentally-measured conditions (room-temp arm, chamber arm), same ambient light,", False),
    ("differing only in temperature and humidity.  The 40C/80%RH extrapolation has been REMOVED.", False),
    ("", False),
    ("Sheets: one per pigment (Vermilion / Malachite / Azurite), both arms, live deltaE formulas.", False),
    ("Means are intentionally NOT precomputed -- aggregate once the measurements are finalised.", False),
]
for i,(txt,bold) in enumerate(readme, 1):
    cc = rm.cell(i,1,txt)
    if bold: cc.font = Font(bold=True)
rm.column_dimensions["A"].width = 110

cols = ["arm_code","condition","status","pigment","geometry","spot","date","day",
        "L*","a*","b*","deltaE","point_type"]
widths = [22,30,20,11,10,9,7,6,8,8,8,9,13]

# ---- one sheet per pigment (data_long / deltaE_mean intentionally omitted) ----
def _split_sheet(name, keep):
    ws = out.create_sheet(name[:31]); ws.append(cols)
    for j in range(1, len(cols)+1):
        ws.cell(1,j).font = hdr_font; ws.cell(1,j).fill = hdr_fill
    write_dE_formula(ws, [r for r in rows_out if keep(r)])
    ws.freeze_panes = "A2"
    for j,w in enumerate(widths,1): ws.column_dimensions[openpyxl.utils.get_column_letter(j)].width = w
for pig in ["Vermilion","Malachite","Azurite"]:              # one sheet per pigment
    _split_sheet(pig, lambda r, p=pig: r[3]==p)

dst="experiments/mogao_data_consolidated.xlsx"
out.save(dst)
print(f"Saved {dst}")
print(f"  sheets: {out.sheetnames}")
print(f"  arms: {[v[1] for v in SHEETS.values()]}")
